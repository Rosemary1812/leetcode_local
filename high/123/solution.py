# ===== 123. 买卖股票的最佳时机 III =====
# 难度: 困难
# 英文名: Best Time to Buy and Sell Stock III
# 来源: https://leetcode.cn/problems/best-time-to-buy-and-sell-stock-iii/description/
#
# 给定一个数组，它的第 i 个元素是一支给定股票第 i 天的价格。
# 设计一个算法来计算你所能获取的最大利润。你最多可以完成两笔交易。
# 注意：你不能同时参与多笔交易（你必须在再次购买前出售掉之前的股票）。
#
# 示例 1：
# 输入：prices = [3,3,5,0,0,3,1,4]
# 输出：6
# 解释：在第 4 天买入，第 6 天卖出，利润为 3；然后在第 7 天买入，第 8 天卖出，利润为 3；总利润为 6。
#
# 示例 2：
# 输入：prices = [1,2,3,4,5]
# 输出：4
# 解释：在第 1 天买入，第 5 天卖出，利润为 4；总利润为 4。
#
# 示例 3：
# 输入：prices = [7,6,4,3,1]
# 输出：0
# 解释：在此情况下，不进行任何交易，最大利润为 0。
#
# ---------------------------------------------------------
from math import inf


def maxProfit(prices):
    k = 2
    f = [[-inf] * 2 for _ in range(k + 2)]
    for j in range(1, k + 2):
        f[j][0] = 0
    for p in prices:
        for j in range(k + 1, 0, -1):
            f[j][0] = max(f[j][0], f[j][1] + p)
            f[j][1] = max(f[j][1], f[j - 1][0] - p)
    return f[-1][0]


print(maxProfit([1, 2, 3, 4, 5]))
print(maxProfit([7, 6, 4, 3, 1]))


